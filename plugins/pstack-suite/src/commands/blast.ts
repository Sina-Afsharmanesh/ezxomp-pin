import type { ExtensionCommandContext } from "@oh-my-pi/pi-coding-agent";
import { createBacklogDoc } from "./backlog-doc.js";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { hasBacklogMd } from "../utils.js";
import { startProgressOverlayForCtx } from "../overlay/progress-overlay.js";
import { beginRun, addAction, finishRun, saveRun } from "../run.js";
import { emitEvent } from "../events.js";

/** Blast radius analysis - scans src/ for imports referencing target path */
export async function handleBlast(args: string, ctx: ExtensionCommandContext): Promise<void> {
  const target = args.trim();
  if (!target) {
    ctx.ui.notify("pstack blast: usage: pstack blast <file-or-dir>", "error");
    return;
  }
  const cwd = ctx.cwd || process.cwd();

  if (!hasBacklogMd()) {
    ctx.ui.notify("pstack blast: backlog CLI not found.", "error");
    return;
  }

  const run = beginRun({ playbook: "blast", phase: "scan", target });
  const abortController = new AbortController();
  const overlayCtrl = startProgressOverlayForCtx(ctx, "blast", {
    runId: run.runId,
    onCancelRequest() {
      abortController.abort();
      // The local AbortController owns this command.
    },
  });

  try {
    emitEvent({ type: "phase", at: new Date().toISOString(), meta: { runId: run.runId, playbook: "blast" }, payload: { phase: "scan", status: "running" } });
    ctx.ui.notify("pstack blast: scanning imports ...", "info");
    const importers = scanImporters(target, cwd, abortController.signal);
    const date = new Date().toISOString().slice(0, 10);
    const title = "Blast radius: " + target;
    const content = formatBlastDoc(target, importers, date);
    const ok = await createBacklogDoc(title, "blast", content, cwd, ctx, "blast", "exec", abortController.signal);
    if (!ok) {
      saveRun(finishRun(addAction(run, "scan", "failed", "backlog document failed"), "failed"), cwd);
      return;
    }
    saveRun(finishRun(addAction(run, "scan", abortController.signal.aborted ? "cancelled" : "ok", `${importers.length} importer(s)`), abortController.signal.aborted ? "cancelled" : "success"), cwd);
    ctx.ui.notify("pstack blast: created '" + title + "' -- " + importers.length + " importer(s) found", "info");
  } finally {
    overlayCtrl?.close();
  }
}

function scanImporters(target: string, cwd: string, signal?: AbortSignal): string[] {
  const importers: string[] = [];
  const srcDir = join(cwd, "src");
  try { scanDir(srcDir, target, importers, signal); } catch {}
  return importers;
}

function scanDir(dir: string, target: string, importers: string[], signal?: AbortSignal): void {
  if (signal?.aborted) return;
  try {
    for (const entry of readdirSync(dir)) {
      if (signal?.aborted) return;
      const full = join(dir, entry);
      if (entry === "node_modules" || entry === ".git" || entry === "dist") continue;
      try {
        const stat = statSync(full);
        if (stat.isDirectory()) { scanDir(full, target, importers, signal); continue; }
        if (entry.endsWith(".ts") || entry.endsWith(".tsx") || entry.endsWith(".js")) {
          const c = readFileSync(full, "utf-8");
          if (c.includes(target)) importers.push(full);
        }
      } catch {}
    }
  } catch {}
}

function formatBlastDoc(target: string, importers: string[], date: string): string {
  const codef = "`";
  const importerList = importers.length
    ? importers.map((f) => "- " + f).join("\n")
    : "No importers found.";
  const risk = importers.length === 0 ? "Low - no known dependencies"
    : importers.length <= 3 ? "Medium - " + importers.length + " known dependency(ies)"
    : "High - " + importers.length + " known dependencies";
  const testTargets = importers.length
    ? importers.map((f) => f.replace(/\.[^.]+$/, "") + ".test.ts").join("\n")
    : "No specific test targets identified.";
  return [
    "# Blast Radius: " + target, "",
    "## File", codef + target + codef, "",
    "## Importers Found", importerList, "",
    "## Risk", risk, "",
    "## Suggested Test Targets", testTargets, "",
    "---", "*Generated by pstack blast on " + date + "*"
  ].join("\n");
}
