import type { ExtensionCommandContext } from "@oh-my-pi/pi-coding-agent";
import { execFile } from "node:child_process";
import { readFileSync, writeFileSync, unlinkSync } from "node:fs";
import { join } from "node:path";
import { hasBacklogMd } from "../utils.js";
import { runProcess, type CommandResult } from "../runner.js";
import { beginRun, addAction, finishRun, saveRun } from "../run.js";
import { startProgressOverlayForCtx } from "../overlay/progress-overlay.js";

/**
 * TDD loop
 * Verify test framework exists (package.json vitest/jest); run tests; report RED/GREEN.
 * With --go flag, loop once.
 * Runs under an optional live progress overlay (headless-safe).
 * @implements TASK-37.7 / TASK-11
 */
export async function handleTdd(args: string, ctx: ExtensionCommandContext): Promise<void> {
  const cwd = ctx.cwd || process.cwd();

  const run = beginRun({ playbook: "tdd", phase: "tests", target: cwd });
  const abortController = new AbortController();
  // Optional progress overlay — created only when a live TUI surface exists.
  const overlayCtrl = startProgressOverlayForCtx(ctx, "tdd", {
    runId: run.runId,
    onCancelRequest() {
      abortController.abort();
      // The local AbortController owns this command.
    },
  });

  try {
    const flags = parseArgs(args);
    const loop = flags.has("go");

    ctx.ui.notify("pstack tdd: detecting test framework ...", "info");
    const framework = detectFramework(cwd);
    if (!framework) {
      saveRun(finishRun(addAction(run, "detect-framework", "failed", "no test framework found"), "failed"), cwd);
      ctx.ui.notify("pstack tdd: no test framework found (vitest/jest not in package.json).", "error");
      return;
    }
    ctx.ui.notify("pstack tdd: found " + framework.name + " (runner: " + framework.runner + ")", "info");

    ctx.ui.notify("pstack tdd: running tests ...", "info");
    const result = await runProcess(framework.args, { cwd, timeoutMs: 120000, signal: abortController.signal, runId: run.runId });

    const status = result.cancelled ? "CANCELLED" : result.exitCode === 0 ? "GREEN" : "RED";
    const receiptStatus = result.cancelled ? "cancelled" : result.exitCode === 0 ? "success" : "failed";
    saveRun(finishRun(addAction(run, "tests", result.cancelled ? "cancelled" : result.exitCode === 0 ? "ok" : "failed", `exit code ${result.exitCode ?? "null"}`), receiptStatus), cwd);
    ctx.ui.notify("pstack tdd: " + status + " (exit code " + result.exitCode + ")", result.exitCode === 0 ? "info" : "error");

    if (loop && result.exitCode !== 0) {
      ctx.ui.notify("pstack tdd: --go flag set, tests are RED — fix and re-run manually.", "info");
    }

    if (hasBacklogMd()) {
      const date = new Date().toISOString().slice(0, 10);
      const title = "TDD run: " + status + " on " + date;
      const content = formatTddDoc(framework.name, result, status, date);
      ctx.ui.notify("pstack tdd: creating backlog document ...", "info");
      const ok = await createBacklogDoc(title, "tdd", content, cwd, ctx);
      if (ok) {
        ctx.ui.notify("pstack tdd: created '" + title + "'", "info");
      }
    }
  } finally {
    overlayCtrl?.close();
  }
}

function parseArgs(raw: string): Set<string> {
  const s = new Set<string>();
  for (const tok of raw.split(" ")) {
    const trimmed = tok.trim();
    if (trimmed.startsWith("--")) s.add(trimmed.slice(2));
  }
  return s;
}

interface TestFramework {
  name: string;
  runner: string;
  args: string[];
}

function detectFramework(cwd: string): TestFramework | undefined {
  const pkgPath = join(cwd, "package.json");
  try {
    const raw = readFileSync(pkgPath, "utf-8");
    const pkg = JSON.parse(raw);
    const deps = { ...pkg.devDependencies, ...pkg.dependencies };
    if (deps["vitest"]) {
      return { name: "vitest", runner: "npx", args: ["npx", "vitest", "run", "--reporter=dot"] };
    }
    if (deps["jest"]) {
      return { name: "jest", runner: "npx", args: ["npx", "jest", "--passWithNoTests"] };
    }
    if (pkg.scripts && pkg.scripts.test) {
      return { name: "npm-test", runner: "npm", args: ["npm", "test"] };
    }
  } catch {}
  return undefined;
}

function formatTddDoc(framework: string, result: CommandResult, status: string, date: string): string {
  const fence = String.fromCharCode(96).repeat(3);
  const lines = [
    "# TDD Run: " + status, "",
    "## Framework", framework, "",
    "## Result", status + " (exit code: " + result.exitCode + ")", "",
    "## Output", (result.stdout || result.stderr) ? fence + "\n" + [result.stdout, result.stderr].filter(Boolean).join("\n") + "\n" + fence : "(no output)", "",
    "---", "*Generated by pstack tdd on " + date + "*"
  ];
  return lines.join("\n");
}

function createBacklogDoc(title: string, p: string, content: string, cwd: string, ctx: ExtensionCommandContext): Promise<boolean> {
  return new Promise((resolve) => {
    const tmpPath = join(cwd, ".pstack-tdd-" + Date.now() + ".md");
    writeFileSync(tmpPath, content);
    execFile("backlog", ["doc", "create", title, "-p", p, "-t", "other"], { cwd, maxBuffer: 1024 * 256 },
      (error, _stdout, stderr) => {
        try { unlinkSync(tmpPath); } catch {}
        if (error) { ctx.ui.notify("pstack tdd: " + (stderr || "backlog doc create failed").slice(0, 300), "error"); resolve(false); return; }
        resolve(true);
      });
  });
}
