import type { ExtensionCommandContext } from "@oh-my-pi/pi-coding-agent";
import { createBacklogDoc } from "./backlog-doc.js";
import { join } from "node:path";
import { hasBacklogMd } from "../utils.js";

/** Design critique with alternatives
 * Creates a backlog research doc with sections: Current approach, Trade-offs, Alternatives, Recommendation.
 * @implements TASK-37.7
 */
export async function handleHow(args: string, ctx: ExtensionCommandContext): Promise<void> {
  const topic = args.trim() || "current approach";
  const cwd = ctx.cwd || process.cwd();

  if (!hasBacklogMd()) {
    ctx.ui.notify("pstack how: backlog CLI not found.", "error");
    return;
  }

  ctx.ui.notify("pstack how: creating design critique for '"+topic+"' ...", "info");
  const date = new Date().toISOString().slice(0, 10);
  const title = "Design critique: "+topic;
  const content = formatCritiqueDoc(topic, date);

  const ok = await createBacklogDoc(title, "research", content, cwd, ctx, "how", "exec");
  if (!ok) {
    ctx.ui.notify("pstack how: failed to create backlog document.", "error");
    return;
  }

  ctx.ui.notify("pstack how: created '"+title+"'", "info");
}

function formatCritiqueDoc(topic: string, date: string): string {
  const fence = String.fromCharCode(96).repeat(3);
  return ["# Design Critique: "+topic,"",
    "## Current Approach",
    "Document the current implementation approach for this topic.",
    "Include code references, architectural decisions, and constraints.",
    "",
    "## Trade-offs",
    "- **Pros**: What works well in the current approach",
    "- **Cons**: Pain points, technical debt, complexity hotspots",
    "- **Cost**: Maintenance burden, cognitive overhead",
    "",
    "## Alternatives",
    "",
    "### Alternative 1: Simplified Approach",
    "- One-line: Reduce complexity by removing abstraction layers",
    "- Trade-off: Lose flexibility for readability",
    "",
    "### Alternative 2: Composition Over Inheritance",
    "- One-line: Replace hierarchy with composable building blocks",
    "- Trade-off: More files, but clearer boundaries",
    "",
    "### Alternative 3: Defer to Existing Library",
    "- One-line: Use battle-tested dependency instead of custom implementation",
    "- Trade-off: External dependency vs. maintained complexity",
    "",
    "## Recommendation",
    "Based on the trade-offs above, recommend the path with the best signal-to-noise ratio.",
    "Consider team velocity, codebase health, and long-term maintenance.",
    "",
    "---","*Generated by pstack how on "+date+"*"].join("\n");
}
