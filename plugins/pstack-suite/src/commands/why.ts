import type { ExtensionCommandContext } from "@oh-my-pi/pi-coding-agent";
import { createBacklogDoc } from "./backlog-doc.js";
import { join } from "node:path";
import { runProcessSync } from "../runner.js";
import { hasBacklogMd } from "../utils.js";

/** Investigate why code exists (git archaeology)
 * Takes <symbol> arg. Runs git log in ctx.cwd; greps commits for symbol;
 * produces a research doc via backlog CLI.
 * @implements TASK-37.7
 */
export async function handleWhy(args: string, ctx: ExtensionCommandContext): Promise<void> {
  const symbol = args.trim();
  if (!symbol) {
    ctx.ui.notify("pstack why: usage: pstack why <symbol>", "error");
    return;
  }
  const cwd = ctx.cwd || process.cwd();
  if (!hasBacklogMd()) {
    ctx.ui.notify("pstack why: backlog CLI not found.", "error");
    return;
  }
  ctx.ui.notify("pstack why: fetching commit history for \'"+symbol+"\' ...", "info");
  const rawLog = await fetchLog(cwd);
  const touching = grepCommits(rawLog, symbol);
  const date = new Date().toISOString().slice(0, 10);
  const importSet = new Set<string>();
  const title = "Why does "+symbol+" exist";
  const docContent = formatWhyDoc(symbol, touching, date);
  ctx.ui.notify("pstack why: creating backlog research document ...", "info");
  const ok = await createBacklogDoc(title, "research", docContent, cwd, ctx, "why");
  if (!ok) {
    ctx.ui.notify("pstack why: failed to create backlog document.", "error");
    return;
  }
  ctx.ui.notify("pstack why: created \'"+title+"\' — "+touching.length+" commit(s) found", "info");
}

function fetchLog(cwd: string): Promise<string> {
  const r = runProcessSync(["git", "log", "-20", "--pretty=format:%h %ai %s%n%b%n---"], { cwd });
  return Promise.resolve((r.stdout + r.stderr).trim());
}

function grepCommits(raw: string, symbol: string): string[] {
  const blocks = raw.split(/---/).filter((b) => b.trim().length > 0);
  const results: string[] = [];
  const symLower = symbol.toLowerCase();
  for (const block of blocks) {
    if (block.toLowerCase().includes(symLower)) results.push(block.trim());
  }
  return results;
}

function formatWhyDoc(symbol: string, commits: string[], date: string): string {
  const fence = String.fromCharCode(96).repeat(3);
  const commitSection = commits.length
    ? commits.map((c) => "\n" + fence + "\n" + c + "\n" + fence).join("\n")
    : "No commits in recent history mention this symbol.";
  const codeFence = String.fromCharCode(96);
  return ["# Why Does "+symbol+" Exist","","## Symbol",codeFence+symbol+codeFence,"",
    "## Recent Commits Touching It",commitSection,"",
    "## First-Seen Commit","Requires broader history search.",
    "Run: git log --all | grep \'"+symbol+"\'",
    "","## Hypotheses","- Added as part of feature implementation (see commits above)",
    "- May be infrastructure/scaffolding code","- Could be a refactoring artifact",
    "","---","*Generated by pstack why on "+date+"*"].join("\n");
}
