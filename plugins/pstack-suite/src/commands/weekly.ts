import type { ExtensionCommandContext } from "@oh-my-pi/pi-coding-agent";
import { writeFileSync, unlinkSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { runProcessSync } from "../runner.js";
import { hasBacklogMd } from "../utils.js";

/** Generate weekly status report
 * Pulls the Git commit log and creates a backlog report doc.
 * @implements TASK-37.8
 */
export async function handleWeekly(args: string, ctx: ExtensionCommandContext): Promise<void> {
  const cwd = ctx.cwd || process.cwd();
  if (!hasBacklogMd()) {
    ctx.ui.notify("pstack weekly: backlog CLI not found.", "error");
    return;
  }
  const range = args.trim() || "7d";
  ctx.ui.notify("pstack weekly: fetching commit history for the last " + range + " ...", "info");
  const rawLog = await fetchLog(cwd, ctx, range);
  const date = new Date().toISOString().slice(0, 10);
  const title = "Weekly status: " + date;
  const docContent = formatWeeklyDoc(rawLog, date);
  ctx.ui.notify("pstack weekly: creating backlog report document ...", "info");
  const ok = await createBacklogDoc(title, "reports", docContent, cwd, ctx);
  if (!ok) {
    ctx.ui.notify("pstack weekly: failed to create backlog document.", "error");
    return;
  }
  ctx.ui.notify("pstack weekly: created \'" + title + "\'", "info");
}

async function fetchLog(cwd: string, ctx: ExtensionCommandContext, range: string): Promise<string> {
  const days = parseInt(range) || 7;
  const since = `${days} days ago`;
  const r = runProcessSync(
    ["git", "log", "--since=" + since, "--oneline", "--no-decorate"],
    { cwd },
  );
  return (r.stdout + r.stderr).trim();
}

function formatWeeklyDoc(rawLog: string, date: string): string {
  const fence = String.fromCharCode(96).repeat(3);
  const logSection = rawLog.trim() ? rawLog : "No commits in recent history.";
  return ["# Weekly Status Report", "", "Date: " + date, "",
    "## Recent Commits", fence, logSection, fence, "",
    "---", "*Generated by pstack weekly on " + date + "*"].join("\n");
}

async function createBacklogDoc(title: string, p: string, content: string, cwd: string, ctx: ExtensionCommandContext): Promise<boolean> {
  const tmpPath = join(tmpdir(), ".pstack-weekly-" + Date.now() + ".md");
  writeFileSync(tmpPath, content);
  const r = runProcessSync(
    ["backlog", "doc", "create", title, "-p", p, "-t", "report"],
    { cwd },
  );
  try { unlinkSync(tmpPath); } catch {}
  if (!r.ok) {
    ctx.ui.notify("pstack weekly: " + (r.stderr || "backlog doc create failed").slice(0, 300), "error");
    return false;
  }
  return true;
}
