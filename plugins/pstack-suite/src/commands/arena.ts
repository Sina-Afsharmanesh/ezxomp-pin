import type { ExtensionCommandContext } from "@oh-my-pi/pi-coding-agent";
import { createBacklogDoc } from "./backlog-doc.js";
import { join } from "node:path";
import { hasBacklogMd } from "../utils.js";
import { startProgressOverlayForCtx } from "../overlay/progress-overlay.js";
import { beginRun, addAction, finishRun, saveRun } from "../run.js";
import { emitEvent } from "../events.js";

/** Multi-runner alternative exploration */
export async function handleArena(args: string, ctx: ExtensionCommandContext): Promise<void> {
  const parts = args.trim().split(/\s+/);
  let topic = "approach comparison";
  let n = 3;
  for (let i = 0; i < parts.length; i++) {
    if (parts[i] === "--n" || parts[i] === "--count") { const next = parts[++i]; if (next) n = parseInt(next, 10) || 3; }
    else { const t = parts[i]; if (t) topic = t; }
  }
  const cwd = ctx.cwd || process.cwd();

  if (!hasBacklogMd()) {
    ctx.ui.notify("pstack arena: backlog CLI not found.", "error");
    return;
  }

  const run = beginRun({ playbook: "arena", phase: "explore", target: topic });
  const abortController = new AbortController();
  const overlayCtrl = startProgressOverlayForCtx(ctx, "arena", {
    runId: run.runId,
    onCancelRequest() {
      abortController.abort();
      // The local AbortController owns this command.
    },
  });

  try {
    emitEvent({ type: "phase", at: new Date().toISOString(), meta: { runId: run.runId, playbook: "arena" }, payload: { phase: "explore", status: "running" } });
    ctx.ui.notify("pstack arena: exploring "+n+" alternatives for '"+topic+"' ...", "info");
    const date = new Date().toISOString().slice(0, 10);
    const title = "Alternatives arena: "+topic;
    const content = formatArenaDoc(topic, n, date);

    const ok = await createBacklogDoc(title, "research", content, cwd, ctx, "arena", "exec", abortController.signal);
    if (!ok) {
      saveRun(finishRun(addAction(run, "explore", "failed", "backlog document failed"), "failed"), cwd);
      ctx.ui.notify("pstack arena: failed to create backlog document.", "error");
      return;
    }

    saveRun(finishRun(addAction(run, "explore", abortController.signal.aborted ? "cancelled" : "ok", `${n} alternatives`), abortController.signal.aborted ? "cancelled" : "success"), cwd);
    ctx.ui.notify("pstack arena: created '"+title+"' with "+n+" alternatives", "info");
  } finally {
    overlayCtrl?.close();
  }
}

function formatArenaDoc(topic: string, n: number, date: string): string {
  const alts = [
    { name: "Approach A", pitch: "Conservative — minimal change, low risk", tradeoffs: "Low risk; slow payoff" },
    { name: "Approach B", pitch: "Balanced — moderate effort, good outcome", tradeoffs: "Medium risk; good balance" },
    { name: "Approach C", pitch: "Aggressive — big change, high payoff", tradeoffs: "High risk; high reward" },
    { name: "Approach D", pitch: "Hybrid — combine best of A and B", tradeoffs: "Moderate complexity; flexible" },
    { name: "Approach E", pitch: "Incremental — smallest viable step", tradeoffs: "Very safe; may need follow-up" },
  ];
  const chosen = alts.slice(0, Math.max(2, n));
  const lines = [];
  lines.push("# Alternatives Arena: "+topic);
  lines.push("");
  for (const alt of chosen) {
    lines.push("## "+alt.name);
    lines.push("- **Pitch**: "+alt.pitch);
    lines.push("- **Trade-offs**: "+alt.tradeoffs);
    lines.push("");
  }
  lines.push("## Summary Table");
  lines.push("");
  lines.push("| Approach | Pitch | Trade-offs |");
  lines.push("|----------|-------|------------|");
  for (const alt of chosen) {
    lines.push("| "+alt.name+" | "+alt.pitch+" | "+alt.tradeoffs+" |");
  }
  lines.push("");
  lines.push("---");
  lines.push("*Generated by pstack arena on "+date+"*");
  return lines.join("\n");
}
